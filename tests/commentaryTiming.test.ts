import { describe, expect, it } from 'vitest'
import { CommentaryTiming } from '../src/audio/CommentaryTiming'

describe('commentary timing', () => {
  it('lets ordinary speech finish and leaves a gap instead of cutting it at the HUD timeout', () => {
    const timing = new CommentaryTiming()
    expect(timing.offer('start', 0, true)).toBe('start')
    expect(timing.offer('quickTip', 2000)).toBeNull()
    timing.complete(3000)
    expect(timing.poll(3849)).toBeNull()
    expect(timing.poll(3850)).toBe('quickTip')
  })
  it('speaks a race event over coaching, so the line lands with its chime and banner', () => {
    const timing = new CommentaryTiming()
    expect(timing.offer('quickTip', 0)).toBe('quickTip')
    expect(timing.offer('overtake', 1500)).toBe('overtake')
    expect(timing.offer('rhythm', 2000)).toBeNull()
    timing.complete(4000)
    // Coaching that queued behind the event has gone stale by then.
    expect(timing.poll(7000)).toBeNull()
  })
  it('follows the start line quickly with a pass that happened during it, or drops it once stale', () => {
    const timing = new CommentaryTiming()
    timing.offer('start', 0, true)
    expect(timing.offer('overtake', 1500)).toBeNull()
    timing.complete(3000)
    expect(timing.poll(3299)).toBeNull()
    expect(timing.poll(3300)).toBe('overtake')
    const late = new CommentaryTiming()
    late.offer('start', 0, true)
    late.offer('overtake', 500)
    late.complete(3000)
    expect(late.poll(3300)).toBeNull()
  })
  it('allows major events to interrupt ordinary speech and drops superseded position cues', () => {
    const timing = new CommentaryTiming()
    timing.offer('quickTip', 0)
    timing.offer('overtake', 500)
    expect(timing.offer('lead', 1000)).toBe('lead')
    expect(timing.offer('lostLead', 1500)).toBe('lostLead')
    expect(timing.offer('finalLap', 2000)).toBe('finalLap')
    expect(timing.offer('finish', 2200)).toBe('finish')
    timing.complete(3000)
    expect(timing.poll(6000)).toBeNull()
  })
  it('drops commentary that is too late to be useful', () => {
    const timing = new CommentaryTiming()
    timing.offer('drift', 0)
    timing.offer('overtake', 1000)
    timing.complete(7000)
    expect(timing.poll(9000)).toBeNull()
  })
  it('spaces ordinary lines even when clips are short', () => {
    const timing = new CommentaryTiming()
    timing.offer('focus', 0)
    timing.complete(1000)
    expect(timing.offer('rhythm', 3000)).toBeNull()
    expect(timing.poll(5999)).toBeNull()
    expect(timing.poll(6000)).toBe('rhythm')
  })
  it('calls back-to-back passes when they happen, not on the coaching spacing', () => {
    const timing = new CommentaryTiming()
    timing.offer('overtake', 0)
    timing.complete(2500)
    expect(timing.offer('overtake', 3000)).toBe('overtake')
  })
  it('keeps timed start cues immediate and cancels old-race work on reset', () => {
    const timing = new CommentaryTiming()
    timing.offer('welcome', 0, true)
    expect(timing.offer('countdown', 1000, true)).toBe('countdown')
    expect(timing.offer('start', 4000, true)).toBe('start')
    timing.offer('overtake', 4500)
    timing.reset()
    expect(timing.poll(8000)).toBeNull()
    expect(timing.offer('welcome', 8100, true)).toBe('welcome')
  })
  it('does not announce an obsolete overtake after the lead changes', () => {
    const timing = new CommentaryTiming()
    timing.offer('finalLap', 0)
    timing.offer('overtake', 100)
    timing.offer('lead', 200)
    timing.complete(1000)
    expect(timing.poll(1850)).toBe('lead')
    timing.complete(2500)
    expect(timing.poll(6000)).toBeNull()
  })
})

it('only reports a quiet stretch after playback completes and queued events are gone', () => {
  const timing = new CommentaryTiming()
  timing.offer('drift', 1000, true)
  expect(timing.quietFor(20000)).toBe(0)
  timing.complete(20000)
  expect(timing.quietFor(32000)).toBe(12000)
  timing.offer('overtake', 32000)
  expect(timing.quietFor(50000)).toBe(0)
})
